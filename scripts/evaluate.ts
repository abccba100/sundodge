// Reproducible evaluation of SunDodge on the bundled areas.
// Picks random walks (seeded), compares the shortest route with the SunDodge route,
// and measures how much the "when to leave" sweep adds. Writes docs/EVALUATION.md.
// Usage: npx tsx scripts/evaluate.ts [tripsPerArea=200]
import { readFileSync, writeFileSync } from 'node:fs';
import { parseOverpass } from '../src/data/osm';
import { Planner, WALK_SPEED } from '../src/engine/planner';
import { shortestPath } from '../src/engine/graph';
import { DEMO_AREAS } from '../src/areas';
import { zonedToDate, parseClock } from '../src/time';

const N = Number(process.argv[2] ?? 200);
const ALPHA = 3; // the app's default: 1 m of sun costs as much as 3 m of shade
const SEED = 20261017;
const TIMES = ['13:00', '15:00', '17:00'];

function mulberry32(a: number) {
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const q = (xs: number[], p: number) => {
  const s = [...xs].sort((a, b) => a - b);
  const i = (s.length - 1) * p, lo = Math.floor(i), hi = Math.ceil(i);
  return s[lo] + (s[hi] - s[lo]) * (i - lo);
};
const f1 = (x: number) => x.toFixed(1);
const pct = (x: number) => `${Math.round(x)}%`;
const share = (xs: number[], ok: (x: number) => boolean) => pct((xs.filter(ok).length / xs.length) * 100);
const triple = (xs: number[], fmt = f1) => `${fmt(q(xs, 0.5))} (${fmt(q(xs, 0.25))}–${fmt(q(xs, 0.75))})`;

const out: string[] = [];
const summary: Record<string, unknown> = {};
out.push('# Evaluation', '');
out.push(`Generated by \`npm run evaluate\` (scripts/evaluate.ts) on the bundled OpenStreetMap areas. Seed ${SEED}, ${N} random walks per area, α = ${ALPHA}. All numbers are model output on OSM data: they measure minutes in direct sun as SunDodge computes it, not measured temperatures or health effects.`, '');
out.push('Method:', '');
out.push('- Walks: random pairs of street nodes 500–1,500 m apart in a straight line, both at least 150 m inside the area edge.');
out.push('- For each walk and departure time, SunDodge finds the shortest route and the SunDodge route, with shadows at mid-walk, exactly as the app does.');
out.push('- "Open streets only" re-runs the SunDodge route with covered ways (arcades, covered alleys, underground and indoor passages) removed, to show how much of the saving depends on them.');
out.push('- "When to leave": the best departure within ±60 min (10-min steps) compared with leaving at 15:00, on the SunDodge route.');
out.push('- Medians with the interquartile range in brackets.', '');

for (const a of DEMO_AREAS) {
  const json = JSON.parse(readFileSync(`public/${a.file}`, 'utf8'));
  const { area, proj } = parseOverpass(json, { id: a.id, name: a.name, bounds: a.bounds });
  const pl = new Planner(area, proj);
  const g = area.graph;
  const rand = mulberry32(SEED);
  const [w, s, e, n] = a.bounds;
  const [x0, y0] = proj.toXY(w, s), [x1, y1] = proj.toXY(e, n);
  const inner: number[] = [];
  for (let i = 0; i < g.nodeX.length; i++) {
    if (!g.nodeInMain[i]) continue;
    const x = g.nodeX[i], y = g.nodeY[i];
    if (x > x0 + 150 && x < x1 - 150 && y > y0 + 150 && y < y1 - 150) inner.push(i);
  }
  const trips: [number, number, { edges: number[]; nodes: number[] }][] = [];
  let guard = 0;
  while (trips.length < N && guard++ < N * 200) {
    const u = inner[Math.floor(rand() * inner.length)], v = inner[Math.floor(rand() * inner.length)];
    const d = Math.hypot(g.nodeX[u] - g.nodeX[v], g.nodeY[u] - g.nodeY[v]);
    if (d < 500 || d > 1500) continue;
    const p = pl.shortestByLength(u, v);
    if (p) trips.push([u, v, p]);
  }

  out.push(`## ${a.name}`, '');
  out.push(`${area.stats.buildings.toLocaleString('en-US')} buildings, ${Math.round(((area.stats.buildingsWithHeight + area.stats.buildingsWithLevels) / area.stats.buildings) * 100)}% with a height or floor count in OSM, ${area.stats.trees.toLocaleString('en-US')} mapped trees. Date ${a.date}.`, '');
  out.push('| leave at | shortest route: min in sun | SunDodge route: min in sun | sun saved, min | sun saved, % | extra walking, min | trips saving ≥ 2 min | of which covered ways, min | saved on open streets only, min |');
  out.push('|---|---|---|---|---|---|---|---|---|');
  const areaSum: Record<string, unknown> = {};
  for (const t of TIMES) {
    const rows = trips.map(([u, v, p]) => {
      const r = pl.compare(u, v, zonedToDate(a.date, parseClock(t), a.tz), ALPHA, p)!;
      const sun = r.snap.sun;
      const open = shortestPath(g, u, v, (k) => (g.edgeCovered[k] ? Infinity : g.edgeLen[k] * (1 - sun[k]) + ALPHA * g.edgeLen[k] * sun[k]));
      const openSun = open ? pl.measureRoute(open.edges, open.nodes, r.snap).sunMinutes : r.shortest.sunMinutes;
      return {
        sh: r.shortest.sunMinutes, sd: r.shady.sunMinutes,
        saved: r.shortest.sunMinutes - r.shady.sunMinutes,
        savedPct: r.shortest.sunMinutes > 0.05 ? ((r.shortest.sunMinutes - r.shady.sunMinutes) / r.shortest.sunMinutes) * 100 : 0,
        extra: r.shady.minutes - r.shortest.minutes,
        covered: r.shady.coveredM / WALK_SPEED / 60,
        openSaved: r.shortest.sunMinutes - Math.min(openSun, r.shortest.sunMinutes),
      };
    });
    const col = (k: keyof (typeof rows)[number]) => rows.map((r) => r[k]);
    out.push(`| ${t} | ${triple(col('sh'))} | ${triple(col('sd'))} | ${triple(col('saved'))} | ${triple(col('savedPct'), pct)} | ${triple(col('extra'))} | ${share(col('saved'), (x) => x >= 2)} | ${triple(col('covered'))} | ${triple(col('openSaved'))} |`);
    areaSum[t] = { shortestSun: q(col('sh'), 0.5), shadySun: q(col('sd'), 0.5), saved: q(col('saved'), 0.5), savedPct: q(col('savedPct'), 0.5), extra: q(col('extra'), 0.5), covered: q(col('covered'), 0.5), openSaved: q(col('openSaved'), 0.5) };
  }
  // When to leave, around 15:00
  const gains = trips.map(([u, v, p]) => {
    const base = parseClock('15:00');
    let now = NaN, best = Infinity;
    for (let k = -6; k <= 6; k++) {
      const r = pl.departure(u, v, zonedToDate(a.date, base + 10 * k, a.tz), ALPHA, p);
      if (!r || r.night) continue;
      if (k === 0) now = r.shadySunMin;
      best = Math.min(best, r.shadySunMin);
    }
    return now - best;
  }).filter(Number.isFinite);
  out.push('');
  out.push(`When to leave (around 15:00): the best departure within ±60 min saves a median ${f1(q(gains, 0.5))} min of sun on the SunDodge route (IQR ${f1(q(gains, 0.25))}–${f1(q(gains, 0.75))}); it saves at least 1 min in ${share(gains, (x) => x >= 1)} of trips. Route choice matters more than timing.`, '');
  areaSum.timing = { median: q(gains, 0.5), p25: q(gains, 0.25), p75: q(gains, 0.75), shareAtLeast1: gains.filter((x) => x >= 1).length / gains.length };
  areaSum.trips = trips.length;
  summary[a.id] = areaSum;
  console.log(a.id, JSON.stringify(areaSum));
}
out.push('## Limits', '');
out.push('- Building heights: where OSM has no height or floor count, the height is estimated from the building type (most of the Seoul area). Results there are less certain.');
out.push('- Wide roads are single centre lines in OSM. Sampling the centre of a wide road can overstate the sun on a sidewalk next to buildings, for the shortest route more than for the SunDodge route.');
out.push('- Shadows are evaluated at the middle of each walk; the shadows moving during the walk are not modelled.');
out.push('- "Minutes in direct sun" is an exposure measure, not a heat-stress or health score.', '');
writeFileSync('docs/EVALUATION.md', out.join('\n'));
writeFileSync('docs/evaluation.json', JSON.stringify({ seed: SEED, alpha: ALPHA, trips: N, summary }, null, 1));
console.log('wrote docs/EVALUATION.md and docs/evaluation.json');
